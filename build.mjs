import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { SERVICE_DEFS, DEFAULT_PREFS } from './src/core.mjs';
import config from './config.mjs';
const source = new URL('./src/', import.meta.url);
const [template, styles, ...modules] = await Promise.all([
  readFile(new URL('index.html', source), 'utf8'), readFile(new URL('styles.css', source), 'utf8'),
  ...['core.mjs', 'icons.mjs', 'app.mjs'].map(name => readFile(new URL(name, source), 'utf8'))
]);
const embeddedConfig = JSON.stringify(config).replace(/</gu, '\\u003c');
const script = `const config = ${embeddedConfig};\n` + modules.map(code => code.replace(/^import .*from ['"].*['"];?\r?\n/gmu, '').replace(/^export /gmu, '')).join('\n');
const hash = createHash('sha256').update(script).digest('base64');
const csp = `default-src 'none'; script-src 'sha256-${hash}'; style-src 'unsafe-inline'; connect-src 'self'; img-src 'self' data:; font-src 'none'; base-uri 'none'; object-src 'none'; form-action 'none'; frame-src 'none'`;
const output = template.replace('__CSP__', csp).replace('__STYLES__', styles.replace(/^@charset .*;\n/u, '')).replace('__SCRIPT__', script);
await mkdir(new URL('./dist/', import.meta.url), { recursive: true });
await mkdir(new URL('./deploy/', import.meta.url), { recursive: true });
await writeFile(new URL('./dist/index.html', import.meta.url), output);
const cap = JSON.stringify({ version: 1, source: 'nas', keys: config.enableHealth ? SERVICE_DEFS.map(s => s.key) : [] });
const nginx = `# NAS navigation v3. Generated by node build.mjs; fixed targets only.
limit_req_zone $binary_remote_addr zone=nas_nav_checks:1m rate=3r/s;
server {
    listen 80;
    listen [::]:80;
    server_name _;
    root /usr/share/nginx/html;
    index index.html;
    add_header X-Content-Type-Options nosniff always;
    add_header Referrer-Policy no-referrer always;
    add_header X-Frame-Options SAMEORIGIN always;
    location / {
        try_files $uri $uri/ =404;
        add_header Cache-Control "no-cache" always;
        add_header X-Content-Type-Options nosniff always;
        add_header Referrer-Policy no-referrer always;
        add_header X-Frame-Options SAMEORIGIN always;
    }
    location ~ /\\. { deny all; }
    location = /api/health {
        limit_except GET { deny all; }
        default_type application/json;
        add_header Cache-Control "no-store" always;
        add_header X-Content-Type-Options nosniff always;
        return ${config.enableHealth ? 200 : 501} '${cap}';
    }
${(config.enableHealth ? SERVICE_DEFS : []).map(service => `    location = /api/health/${service.key} {
        include /etc/nginx/nav-health-common.conf;
        proxy_pass http://${DEFAULT_PREFS.lanHost}:${service.port}/;
    }`).join('\n')}
    location @nav_health_redirect {
        add_header X-NAS-Upstream-Status $upstream_status always;
        add_header X-NAS-Upstream-Time $upstream_header_time always;
        add_header X-NAS-Check-From nas always;
        add_header Cache-Control "no-store" always;
        return 204;
    }
}
`;
const common = `# Only bodyless HEAD requests may probe a fixed service root.
limit_except HEAD { deny all; }
limit_req zone=nas_nav_checks burst=15 nodelay;
limit_req_status 429;
set $args "";
proxy_method GET;
proxy_pass_request_body off;
proxy_pass_request_headers off;
proxy_set_header Host $proxy_host;
proxy_set_header Connection "";
proxy_set_header User-Agent "NAS-Navigation-Check/3.0";
proxy_set_header Accept "*/*";
proxy_connect_timeout 2s;
proxy_read_timeout 4s;
proxy_send_timeout 4s;
proxy_hide_header WWW-Authenticate;
proxy_hide_header Set-Cookie;
proxy_redirect off;
proxy_intercept_errors on;
error_page 301 302 303 307 308 = @nav_health_redirect;
add_header X-NAS-Upstream-Status $upstream_status always;
add_header X-NAS-Upstream-Time $upstream_header_time always;
add_header X-NAS-Check-From nas always;
add_header Cache-Control "no-store" always;
access_log off;
`;
await writeFile(new URL('./deploy/default.conf', import.meta.url), nginx);
await writeFile(new URL('./deploy/nav-health-common.conf', import.meta.url), common);
console.log(`Built dist/index.html (${Buffer.byteLength(output)} bytes), CSP hash and fixed Nginx health routes.`);
